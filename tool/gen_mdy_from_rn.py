#!/usr/bin/env python3
"""Sinh token + icon cho bộ UI clone RN (lib/core/ui/mdy/*.g.dart).

    python3 tool/gen_mdy_from_rn.py ../../MindyMobile_Admin

Nguồn: src/components/ui/{tokens,symbols,symbols-filled}.json của MindyMobile_Admin.
Không sửa file .g.dart bằng tay; sửa RN rồi chạy lại.
"""
import json, os, re, sys

rn = sys.argv[1] if len(sys.argv) > 1 else '../MindyMobile_Admin'
ui = os.path.join(rn, 'src/components/ui')
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, 'lib/core/ui/mdy')
os.makedirs(out, exist_ok=True)
tokens = json.load(open(os.path.join(ui, 'tokens.json')))
symbols = json.load(open(os.path.join(ui, 'symbols.json')))
filled = json.load(open(os.path.join(ui, 'symbols-filled.json')))


def color(v):
    v = v.strip()
    if v == 'transparent':
        return 'Color(0x00000000)'
    m = re.fullmatch(r'#([0-9a-fA-F]{6})', v)
    if m:
        return f'Color(0xFF{m.group(1).upper()})'
    m = re.fullmatch(r'rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)', v)
    if m:
        r, g, b, a = int(m.group(1)), int(m.group(2)), int(m.group(3)), float(m.group(4))
        return f'Color(0x{round(a * 255):02X}{r:02X}{g:02X}{b:02X})'
    raise ValueError(v)


def camel(s):
    parts = re.split(r'[-_]', s)
    return parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])


keys = list(tokens['light'].keys())
assert keys == list(tokens['dark'].keys()) or set(keys) == set(tokens['dark'].keys())
L = []
L.append('// GENERATED by tool/gen_mdy_from_rn.py from MindyMobile_Admin tokens.json. DO NOT EDIT.')
L.append("import 'package:flutter/material.dart';\n")
L.append('/// Bảng màu RN (`tokens.json`) dạng ThemeExtension: `context.mdy.primary`.')
L.append('@immutable')
L.append('class MdyPalette extends ThemeExtension<MdyPalette> {')
L.append('  const MdyPalette({')
for k in keys:
    L.append(f'    required this.{k},')
L.append('  });\n')
for k in keys:
    L.append(f'  final Color {k};')
for mode in ('light', 'dark'):
    L.append(f'\n  static const {mode} = MdyPalette(')
    for k in keys:
        L.append(f'    {k}: {color(tokens[mode][k])},')
    L.append('  );')
L.append('\n  @override')
L.append('  MdyPalette copyWith() => this;\n')
L.append('  @override')
L.append('  MdyPalette lerp(covariant MdyPalette? other, double t) {')
L.append('    if (other == null) return this;')
L.append('    return MdyPalette(')
for k in keys:
    L.append(f'      {k}: Color.lerp({k}, other.{k}, t)!,')
L.append('    );')
L.append('  }')
L.append('}\n')


def num_class(name, doc, data, prefix):
    L.append(f'/// {doc}')
    L.append(f'abstract final class {name} {{')
    for k, v in data.items():
        ident = camel(k.replace(prefix, '', 1)) if prefix else camel(k)
        if re.match(r'^\d', ident):
            ident = 's' + ident
        L.append(f'  static const double {ident} = {float(v)};')
    L.append('}\n')


L.append('/// Spacing RN `space-N` -> `MdySpace.sN`.')
L.append('abstract final class MdySpace {')
for k, v in sorted(tokens['spacing'].items(), key=lambda kv: kv[1]):
    L.append(f'  static const double s{k.split("-")[1]} = {float(v)};')
L.append('}\n')
L.append('/// Radius RN `radius-N` -> `MdyRadius.rN`.')
L.append('abstract final class MdyRadius {')
for k, v in sorted(tokens['radius'].items(), key=lambda kv: kv[1]):
    L.append(f'  static const double r{k.split("-")[1]} = {float(v)};')
L.append('}\n')
L.append('/// Thời lượng animation RN (`motion`).')
L.append('abstract final class MdyMotion {')
for k, v in tokens['motion'].items():
    L.append(f'  static const {k} = Duration(milliseconds: {v});')
L.append('}\n')
num_class('MdyLayout', 'Hằng layout RN (`layout`).', tokens['layout'], '')
num_class('MdyLetterSpacing', 'Letter spacing RN.', tokens['letterSpacing'], '')
open(os.path.join(out, 'mdy_tokens.g.dart'), 'w').write('\n'.join(L))

I = []
I.append('// GENERATED by tool/gen_mdy_from_rn.py from MindyMobile_Admin symbols*.json. DO NOT EDIT.')
I.append('// Material Symbols Rounded weight 300 (license: assets/MaterialSymbols-LICENSE.txt bên RN, Apache-2.0).\n')
I.append('/// Tên icon giữ đúng tên RN (snake_case -> camelCase): RN `calendar_month` = `MdyIcons.calendarMonth`.')
I.append('enum MdyIcons {')
# Native video controls replace the RN video player's built-in pause button.
symbols.setdefault('pause', {'viewBox':'0 -960 960 960','path':'M360-240q-17 0-28.5-11.5T320-280v-400q0-17 11.5-28.5T360-720q17 0 28.5 11.5T400-680v400q0 17-11.5 28.5T360-240Zm240 0q-17 0-28.5-11.5T560-280v-400q0-17 11.5-28.5T600-720q17 0 28.5 11.5T640-680v400q0 17-11.5 28.5T600-240Z'})
names = list(symbols.keys())
for n in names:
    s = symbols[n]
    I.append(f"  {camel(n)}('{n}', '{s['viewBox']}', '{s['path']}'),")
I[-1] = I[-1][:-1] + ';'
I.append('\n  const MdyIcons(this.rnName, this.viewBox, this.path);')
I.append('  final String rnName;')
I.append('  final String viewBox;')
I.append('  final String path;')
I.append('\n  /// Biến thể FILL 1 (chỉ có cho light_mode/dark_mode/contrast như RN).')
I.append('  String? get filledPath => switch (this) {')
for n, s in filled.items():
    I.append(f"    MdyIcons.{camel(n)} => '{s['path']}',")
I.append('    _ => null,')
I.append('  };')
I.append('}\n')
open(os.path.join(out, 'mdy_icons.g.dart'), 'w').write('\n'.join(I))
print('ok', len(keys), 'colors', len(names), 'icons')
